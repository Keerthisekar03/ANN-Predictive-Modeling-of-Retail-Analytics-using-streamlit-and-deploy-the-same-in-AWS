import pandas as pd
import numpy as np
import torch
import torch.nn as nn
from torch.utils.data import Dataset, DataLoader
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
import matplotlib.pyplot as plt
import joblib
import os

os.makedirs("models", exist_ok=True)
os.makedirs("outputs/evaluation", exist_ok=True)

# ── Reproducibility ────────────────────────────────────────────────────────────
SEED = 42
torch.manual_seed(SEED)
np.random.seed(SEED)
DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print(f"Using device: {DEVICE}")

# ── 1. Load Data ───────────────────────────────────────────────────────────────
df = pd.read_csv("data/featured_data.csv", parse_dates=["Date"])

FEATURE_COLS = [
    "Store", "Dept", "Type", "Size", "SizeBucket",
    "IsHoliday", "Week", "Month", "Quarter", "Year", "DayOfYear",
    "Week_sin", "Week_cos", "Month_sin", "Month_cos",
    "Temperature", "Fuel_Price", "CPI", "Unemployment",
    "MarkDown1", "MarkDown2", "MarkDown3", "MarkDown4", "MarkDown5",
    "TotalMarkdown", "AnyMarkdown", "Markdown_x_Holiday",
    "Sales_Lag_1", "Sales_Lag_2", "Sales_Lag_4", "Sales_Lag_8",
    "Sales_Lag_13", "Sales_Lag_26", "Sales_Lag_52",
    "Sales_RollMean_4", "Sales_RollMean_8", "Sales_RollMean_13",
    "Sales_RollStd_4", "Sales_RollStd_8", "Sales_RollStd_13",
]
TARGET = "Weekly_Sales"

# ── 2. Train / Test Split (time-based) ────────────────────────────────────────
split_date = "2012-07-01"
train_df = df[df["Date"] < split_date]
test_df  = df[df["Date"] >= split_date]
print(f"Train: {len(train_df):,}  |  Test: {len(test_df):,}")

X_train = train_df[FEATURE_COLS].values.astype(np.float32)
y_train = train_df[TARGET].values.astype(np.float32)
X_test  = test_df[FEATURE_COLS].values.astype(np.float32)
y_test  = test_df[TARGET].values.astype(np.float32)

# ── 3. Scaling ─────────────────────────────────────────────────────────────────
scaler_X = StandardScaler()
scaler_y = StandardScaler()

X_train = scaler_X.fit_transform(X_train)
X_test  = scaler_X.transform(X_test)
y_train_scaled = scaler_y.fit_transform(y_train.reshape(-1, 1)).ravel()
y_test_scaled  = scaler_y.transform(y_test.reshape(-1, 1)).ravel()

joblib.dump(scaler_X, "models/scaler_X.pkl")
joblib.dump(scaler_y, "models/scaler_y.pkl")

# ── 3. Scaling ─────────────────────────────────────────────────────────────────
scaler_X = StandardScaler()
scaler_y = StandardScaler()

X_train = scaler_X.fit_transform(X_train)
X_test  = scaler_X.transform(X_test)
y_train_scaled = scaler_y.fit_transform(y_train.reshape(-1, 1)).ravel()
y_test_scaled  = scaler_y.transform(y_test.reshape(-1, 1)).ravel()

joblib.dump(scaler_X, "models/scaler_X.pkl")
joblib.dump(scaler_y, "models/scaler_y.pkl")

# ── 4. PyTorch Dataset ─────────────────────────────────────────────────────────
class SalesDataset(Dataset):
    def __init__(self, X, y):
        self.X = torch.tensor(X, dtype=torch.float32)
        self.y = torch.tensor(y, dtype=torch.float32).unsqueeze(1)

    def __len__(self):
        return len(self.X)

    def __getitem__(self, idx):
        return self.X[idx], self.y[idx]

BATCH_SIZE = 512
train_loader = DataLoader(SalesDataset(X_train, y_train_scaled),
                          batch_size=BATCH_SIZE, shuffle=True)
test_loader  = DataLoader(SalesDataset(X_test,  y_test_scaled),
                          batch_size=BATCH_SIZE, shuffle=False)

# ── 5. ANN Architecture ────────────────────────────────────────────────────────
class SalesANN(nn.Module):
    """
    Deep ANN with:
      - 4 hidden layers (512 → 256 → 128 → 64)
      - BatchNorm + Dropout for regularization
      - ReLU activations
    """
    def __init__(self, input_dim):
        super().__init__()
        self.net = nn.Sequential(
            # Layer 1
            nn.Linear(input_dim, 512),
            nn.BatchNorm1d(512),
            nn.ReLU(),
            nn.Dropout(0.3),
            # Layer 2
            nn.Linear(512, 256),
            nn.BatchNorm1d(256),
            nn.ReLU(),
            nn.Dropout(0.3),
            # Layer 3
            nn.Linear(256, 128),
            nn.BatchNorm1d(128),
            nn.ReLU(),
            nn.Dropout(0.2),
            # Layer 4
            nn.Linear(128, 64),
            nn.BatchNorm1d(64),
            nn.ReLU(),
            nn.Dropout(0.1),
            # Output
            nn.Linear(64, 1),
        )

    def forward(self, x):
        return self.net(x)

model = SalesANN(input_dim=X_train.shape[1]).to(DEVICE)
print(f"\nModel:\n{model}")
total_params = sum(p.numel() for p in model.parameters() if p.requires_grad)
print(f"Trainable parameters: {total_params:,}")

# ── 6. Loss, Optimizer, Scheduler ─────────────────────────────────────────────
criterion = nn.HuberLoss(delta=1.0)          # robust to outliers
optimizer = torch.optim.AdamW(model.parameters(), lr=1e-3, weight_decay=1e-4)
scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
    optimizer, mode="min", patience=5, factor=0.5
)

# ── 7. Training Loop ───────────────────────────────────────────────────────────
EPOCHS = 80
PATIENCE = 10

train_losses, val_losses = [], []
best_val_loss = float("inf")
patience_counter = 0

for epoch in range(1, EPOCHS + 1):
    # -- Train
    model.train()
    running_loss = 0.0
    for X_batch, y_batch in train_loader:
        X_batch, y_batch = X_batch.to(DEVICE), y_batch.to(DEVICE)
        optimizer.zero_grad()
        preds = model(X_batch)
        loss  = criterion(preds, y_batch)
        loss.backward()
        nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
        optimizer.step()
        running_loss += loss.item() * len(X_batch)

    train_loss = running_loss / len(train_loader.dataset)

    # -- Validate
    model.eval()
    val_running = 0.0
    with torch.no_grad():
        for X_batch, y_batch in test_loader:
            X_batch, y_batch = X_batch.to(DEVICE), y_batch.to(DEVICE)
            preds = model(X_batch)
            val_running += criterion(preds, y_batch).item() * len(X_batch)

    val_loss = val_running / len(test_loader.dataset)
    scheduler.step(val_loss)

    train_losses.append(train_loss)
    val_losses.append(val_loss)

    if epoch % 10 == 0 or epoch == 1:
        print(f"Epoch {epoch:3d}/{EPOCHS}  |  Train Loss: {train_loss:.5f}  |  Val Loss: {val_loss:.5f}")

    # -- Early Stopping
    if val_loss < best_val_loss:
        best_val_loss = val_loss
        patience_counter = 0
        torch.save(model.state_dict(), "models/best_ann_model.pt")
    else:
        patience_counter += 1
        if patience_counter >= PATIENCE:
            print(f"\nEarly stopping at epoch {epoch}")
            break

# ── 8. Load Best Model & Predict ──────────────────────────────────────────────
model.load_state_dict(torch.load("models/best_ann_model.pt", map_location=DEVICE))
model.eval()

all_preds, all_true = [], []
with torch.no_grad():
    for X_batch, y_batch in test_loader:
        preds = model(X_batch.to(DEVICE)).cpu().numpy()
        all_preds.extend(preds)
        all_true.extend(y_batch.numpy())

# Inverse-transform to original scale
y_pred_orig = scaler_y.inverse_transform(
    np.array(all_preds).reshape(-1, 1)).ravel()
y_true_orig = scaler_y.inverse_transform(
    np.array(all_true).reshape(-1, 1)).ravel()

# ── 9. Evaluation Metrics ──────────────────────────────────────────────────────
mae  = mean_absolute_error(y_true_orig, y_pred_orig)
mse  = mean_squared_error(y_true_orig, y_pred_orig)
rmse = np.sqrt(mse)
r2   = r2_score(y_true_orig, y_pred_orig)

print("\n" + "="*50)
print("  OVERALL MODEL EVALUATION (Test Set)")
print("="*50)
print(f"  MAE  : ${mae:,.2f}")
print(f"  MSE  : {mse:,.2f}")
print(f"  RMSE : ${rmse:,.2f}")
print(f"  R²   : {r2:.4f}")
print("="*50)

# ── 10. Holiday vs Non-Holiday Performance ────────────────────────────────────
test_results = test_df[["Date", "Store", "Dept", "IsHoliday", "Weekly_Sales"]].copy()
test_results["Predicted_Sales"] = y_pred_orig

holiday_res    = test_results[test_results["IsHoliday"] == 1]
nonholiday_res = test_results[test_results["IsHoliday"] == 0]

