"""
STEP 1: Data Cleaning and Preprocessing
ANN Retail Sales Forecasting Project (PyTorch)
"""

import pandas as pd
import numpy as np
import os

sales_df    = pd.read_csv("sales_data_set.csv")
features_df = pd.read_csv("Features_data_set.csv")
stores_df   = pd.read_csv("stores_data_set.csv")

print(f"Sales shape    : {sales_df.shape}")
print(f"Features shape : {features_df.shape}")
print(f"Stores shape   : {stores_df.shape}")

# ── 2. Convert Date Columns ────────────────────────────────────────────────────
for df in [sales_df, features_df]:
    df["Date"] = pd.to_datetime(df["Date"], dayfirst=True)

# ── 3. Merge All Three DataFrames ─────────────────────────────────────────────
df = sales_df.merge(features_df, on=["Store", "Date", "IsHoliday"], how="left")
df = df.merge(stores_df, on="Store", how="left")

print(f"\nMerged shape: {df.shape}")
print(df.head(3))

# ── 4. Handle Missing Values ───────────────────────────────────────────────────
print("\nMissing values before treatment:")
print(df.isnull().sum())

# MarkDown columns: fill NA with 0 (no markdown event)
markdown_cols = ["MarkDown1", "MarkDown2", "MarkDown3", "MarkDown4", "MarkDown5"]
df[markdown_cols] = df[markdown_cols].fillna(0)

# CPI and Unemployment: forward-fill within each store
df = df.sort_values(["Store", "Dept", "Date"])
df["CPI"]          = df.groupby("Store")["CPI"].transform(lambda x: x.ffill().bfill())
df["Unemployment"] = df.groupby("Store")["Unemployment"].transform(lambda x: x.ffill().bfill())

print("\nMissing values after treatment:")
print(df.isnull().sum())

# ── 5. Remove Negative Weekly_Sales (returns/errors) ──────────────────────────
neg_mask = df["Weekly_Sales"] < 0
print(f"\nNegative sales rows removed: {neg_mask.sum()}")
df = df[~neg_mask].reset_index(drop=True)

# ── 6. Data Types ─────────────────────────────────────────────────────────────
df["IsHoliday"] = df["IsHoliday"].astype(int)
df["Type"]      = df["Type"].map({"A": 0, "B": 1, "C": 2})   # label-encode store type

# ── 7. Save Cleaned Data ───────────────────────────────────────────────────────
os.makedirs("data", exist_ok=True)
df.to_csv("data/cleaned_data.csv", index=False)
print(f"\nCleaned data saved → data/cleaned_data.csv  |  Shape: {df.shape}")
print("\nColumn dtypes:\n", df.dtypes)

